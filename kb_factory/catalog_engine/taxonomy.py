def _need_text(need: dict) -> dict:
    return {"domain": need["domain"], "intent": need["intent"],
            "kws": "".join(need["keywords"])}


def match_seed(need: dict) -> dict:
    """先匹配种子：六域强别名命中→six_domains；否则中图法骨架→clc。"""
    t = _need_text(need)
    if any(a in t["domain"] or a in t["intent"] or a in t["kws"] for a in SIX_STRONG_ALIASES):
        return {"mode": "six_domains", "seed_taxonomy": [SEED_SIX, SEED_CLC]}
    return {"mode": "clc", "seed_taxonomy": [SEED_CLC]}


def _clc_scores(need: dict):
    """中图法 22 类对需求的相关分（确定性：域 3 分 / 意图 2 分 / 关键词 2 分，别名逐个计）。"""
    t = _need_text(need)
    scored = []
    for i, c in enumerate(CLC_22):
        s = 0
        for a in c["aliases"]:
            if a in t["domain"]:
                s += 3
            if a in t["intent"]:
                s += 2
            if a in t["kws"]:
                s += 2
        scored.append((-s, i, c))
    scored.sort()  # (-score, 类目 canonical 序) → 全确定
    return scored


def pick_l1(need: dict, plan: dict, mode: str) -> list:
    """选 L1 大类：六域模式=六库全上+中图法补位；clc 模式=相关分 Top-N。
    返回 [{code,name,theme,source,seed_topics}]，长度=plan['l1']（恒 ≥8，不足从术语库扩）。"""
    n = plan["l1"]
    if mode == "six_domains":
        out = [{"code": v["code"], "name": v["name"], "theme": f"{v['name']}（{v['code']}）：{v['desc']}",
                "source": SEED_SIX, "seed_topics": list(v["groups"])} for v in SIX_DOMAINS]
        for _, _, c in _clc_scores(need)[: max(n - len(out), 2)]:
            out.append(_clc_spec(c))
        return out
    return [_clc_spec(c) for _, _, c in _clc_scores(need)[:n]]


def _clc_spec(c: dict) -> dict:
    return {"code": c["code"], "name": c["name"], "theme": f"中图法 {c['code']} {c['name']}：{c['name']}主题资料整编",
            "source": SEED_CLC, "seed_topics": list(c["topics"])}


def build_l2_topics(spec: dict, need: dict, plan_l2: int) -> list:
    """L2 主题组：种子主题组优先，不足按 关键词×术语库 模板确定性扩容，去重。"""
    out, seen = [], set()

    def add(name):
        if name and name not in seen:
            seen.add(name)
            out.append(name)

    for t in spec["seed_topics"]:
        add(t)
    # 扩容模板：关键词×术语库 → 意图/域总览 → 编号专题兜底
    cands = [f"{kw}{term}" for kw in need["keywords"] for term in EXPANSION_TERM_BANK]
    cands += [f"{need['intent']}导读", f"{need['domain']}总览"]
    k = 1
    while len(out) < plan_l2:
        if cands:
            add(cands.pop(0))
        else:
            add(f"{spec['name']}专题{k:02d}")
            k += 1
    return out[:plan_l2]
