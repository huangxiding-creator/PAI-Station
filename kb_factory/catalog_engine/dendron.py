# ── 稳定节点 ID ─────────────────────────────────────────────────────────────

def _hash_code(segment: str) -> str:
    """单段内容哈希短码：blake2b(命名空间盐|段dir, 4字节) → 8 位 hex（32bit）。"""
    return hashlib.blake2b(f"{_NS}|{segment}".encode("utf-8"),
                           digest_size=4).hexdigest()


def _split_path(path) -> list:
    """路径切段：统一斜杠、去空段（尾斜杠/重复斜杠/反斜杠均容忍）。"""
    return [p for p in str(path).replace("\\", "/").split("/") if p]


def stable_id(path: str) -> str:
    """路径 → 分层级稳定节点 ID：ddn. + 各段内容哈希短码链（点分，致敬 Dendron
    域点分层命名）。

    例：stable_id("T/TV/水利工程") == stable_id("T") + "." + h("TV") + "." + h("水利工程")
    稳定性：每段只哈希【本段自身内容】，ID=父ID+段短码 —— 与兄弟多少/先后无关，
    增删/重排兄弟不改变其余节点 ID。空路径抛 ValueError，非字符串抛 TypeError。
    """
    if not isinstance(path, str):
        raise TypeError(f"stable_id: 路径须为 str，得到 {type(path).__name__}")
    parts = _split_path(path)
    if not parts or all(not p.strip() for p in parts):
        raise ValueError("stable_id: 路径为空")
    node_id = _ID_PREFIX
    for part in parts:
        node_id = f"{node_id}.{_hash_code(part)}"
    return node_id


def _safe_dir(text: str) -> str:
    """dir 消歧：借用区间类号（I3/7）中的斜杠换连字符，防路径段歧义。"""
    return text.replace("/", "-")


