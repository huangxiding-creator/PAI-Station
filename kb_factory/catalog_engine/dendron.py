def _root_node(key: str, name: str) -> dict:
    """根节点（L1=大类本体）。"""
    return {
        "code": key, "dir": key, "path": f"{key}/", "name": name,
        "theme": f"{name}（{key}）：中图法大类·Dendron 模板兜底层",
        "source": _SOURCE, "origin": "dendron", "stable_id": "", "ratio": 1.0,
    }


def _group_node(g: dict, root_path: str) -> dict:
    """L2 模板组节点（键族对齐 seeds 分组，另带模板/子组数/配比）。"""
    code = g["code"]
    d = _safe_dir(code) if code else _safe_dir(g["name"])
    theme = (f"{g['name']}（{code}）：L2 模板组" if code
             else f"{g['name']}：L2 模板组（补组，无类号）")
    return {
        "code": code, "dir": d, "path": root_path + d + "/", "name": g["name"],
        "theme": theme, "source": _SOURCE, "origin": "dendron", "stable_id": "",
        "ratio": 0.0, "template": g["template"], "slot_count": len(g["slots"]),
        "share": g["share"],
    }


def _slot_node(slot: str, g: dict, group: dict) -> dict:
    """L3 槽位节点：名字=命名模板套槽位（Dendron 模板机制的纯规则等价物）。"""
    rendered = g["template"].format(slot=slot) if "{slot}" in g["template"] else slot
    return {
        "code": None, "dir": rendered, "path": group["path"] + rendered + "/",
        "name": rendered,
        "theme": f"{rendered}：{group['name']}·槽位展开",
        "source": _SOURCE, "origin": "dendron", "stable_id": "", "ratio": 0.0,
        "slot": slot,
    }


def _assign_sibling_ids(nodes: list, parent_id: str) -> None:
    """兄弟组内分配稳定 ID（就地）：base=父ID+段哈希；同父哈希冲突按兄弟序加 -k
    消歧（仅波及冲突者）。子层键仅 l2/l3（深度硬控，无 l4）。"""
    seen: dict = {}
    for node in nodes:
        base = f"{parent_id}.{_hash_code(node['dir'])}"
        k = seen.get(base, 0) + 1
        seen[base] = k
        node["stable_id"] = base if k == 1 else f"{base}-{k}"
        for child_key in ("l2", "l3"):
            if child_key in node:
                _assign_sibling_ids(node[child_key], node["stable_id"])


def expand(schema_key: str, max_depth: Optional[int] = None,
           schema: Optional[dict] = None) -> Optional[dict]:
    """按 schema 递归展开三级目录树（冷门领域模板兜底层）。

    参数：schema_key=22 大类类号之一（大小写/空白容忍）；max_depth 钳制进 [1,3]；
    schema 缺省 SCHEMA_22（传自定义 schema 供测试/接线侧复用）。
    返回 {"mode": "dendron_expand", "schema_key": K, "root": "K 大类名",
          "l1": [根节点(l2=组(l3=槽位…))]}；schema_key 非法/库外 → None（fail-soft）。
    节点键族对齐 seeds 分组（code/dir/path/name/theme/source）另加：
    origin="dendron" + stable_id + ratio；组节点带 template/slot_count/share，
    槽位节点带 slot（与 clc 层输出键可区分：clc 层无 origin/stable_id、
    带 clc_level）。
    """
    table = SCHEMA_22 if schema is None else schema
    if not isinstance(schema_key, str):
        return None
    key = schema_key.strip().upper()
    spec = table.get(key)
    if spec is None:
        return None
    depth = HARD_MAX_DEPTH if max_depth is None else max_depth
    depth = max(min(depth, HARD_MAX_DEPTH), 1)  # 深度硬控：钳进 [1, 3]

    root = _root_node(key, spec["name"])
    if depth >= 2:
        total_share = sum(g["share"] for g in spec["groups"]) or 1
        root["l2"] = []
        for g in spec["groups"]:
            grp = _group_node(g, root["path"])
            grp["ratio"] = round(g["share"] / total_share, 6)
            if depth >= 3:
                grp["l3"] = [_slot_node(s, g, grp) for s in g["slots"]]
                unit = grp["ratio"] / max(len(g["slots"]), 1)
                for leaf in grp["l3"]:
                    leaf["ratio"] = round(unit, 6)
            root["l2"].append(grp)
    _assign_sibling_ids([root], _ID_PREFIX)
    return {"mode": "dendron_expand", "schema_key": key,
            "root": f"{key} {spec['name']}", "l1": [root]}


def refresh_ids(tree: dict) -> dict:
    """全树就地重算 stable_id（供外部增删/重排节点后修复 ID；返回入参树）。

    接受 expand 的整树（含 mode/l1 键）或裸节点；重算规则与 expand 完全一致
    （父ID+段哈希，同父冲突 -k 消歧），因此「增删兄弟后 refresh」幸存节点 ID
    逐字节不变（负例测试实证）。
    """
    root = tree["l1"][0] if isinstance(tree, dict) and "l1" in tree else tree
    _assign_sibling_ids([root], _ID_PREFIX)
    return tree


def schema_stats(schema: Optional[dict] = None) -> dict:
    """种子规模盘点（接线侧烟测/指标用；数字由 SCHEMA_22 实数得出，零手填）。"""
    table = SCHEMA_22 if schema is None else schema
    groups = [g for spec in table.values() for g in spec["groups"]]
    return {
        "classes": len(table),
        "groups": len(groups),
        "aligned_groups": sum(1 for g in groups if g["code"]),
        "authored_groups": sum(1 for g in groups if not g["code"]),
        "slots": sum(len(g["slots"]) for g in groups),
    }
