def _g(code, name, share, slots, template="{slot}"):
    """L2 模板组构造：code=中图法真实二级类号（补组为 None）；share=槽位配比原始
    份额（展开时类内归一为 ratio）；slots=槽位清单（子组数=len(slots)，组内两两
    不重）；template=命名模板（恰含一个 {slot} 占位符）。"""
    return {"code": code, "name": name, "template": template,
            "slots": list(slots), "share": share}


def _cls(name, groups):
    """大类 schema 构造：name=中图法大类名；groups=6-12 个 L2 模板组。"""
    return {"name": name, "groups": list(groups)}


