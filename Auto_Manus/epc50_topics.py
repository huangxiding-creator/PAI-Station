def build() -> dict:
    tree = {"company": COMPANY, "short": SHORT, "alt": list(ALT),
            "generated": time.strftime("%Y-%m-%dT%H:%M:%S"),
            "dimensions": [], "topics": []}
    tid = 0
    for dim, topics in DIMS.items():
        tree["dimensions"].append(
            {"id": dim, "topic_count": len(topics)})
        for title, queries in topics:
            tid += 1
            # 检索词组合: 企业名×查询词 的三形态
            full_queries = [f"{COMPANY} {q}" for q in queries]
            full_queries += [f"{SHORT} {q.split()[0]}" for q in queries[:1]]
            tree["topics"].append({
                "id": f"T{tid:03d}", "dimension": dim, "title": title,
                "queries": full_queries,
                "manus_use": "research_plan" if tid % 3 else "survey_plan",
                "status": "pending", "chars": 0})
    return tree


def main() -> None:
    tree = build()
    out = BATTLE / "_pipeline" / "epc50_topic_tree.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(tree, ensure_ascii=False, indent=1),
                   encoding="utf-8")
    print(f"[主题树] {len(tree['topics'])} 主题 × {len(tree['dimensions'])} 维度"
          f" → {out}")


if __name__ == "__main__":
    main()
