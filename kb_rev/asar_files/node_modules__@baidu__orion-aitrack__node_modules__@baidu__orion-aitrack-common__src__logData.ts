import {debugerror} from './debug';
import {aitErrorMessages, AitErrorCodes} from './error';

// 事件的动作
export enum AitBehavior {
    SHOW = 'show',
    CLICK = 'click',
    EVENT = 'event',
    HOVER = 'hover',
    DURATION = 'duration'
}

export interface AitActionData {
    des: string;
    value: string;
    behavior: AitBehavior;
    actId?: number | string;
    // 延迟上报时间（应用与展现上报）
    delay?: number;
    // 唯一标识
    ccode?: string | boolean;
    customParams?: Record<string, any>;
}

export interface AitLogData {
    des: string;
    module: string;
    customParams?: Record<string, any>;
    // 是否忽略上传
    ignoreUpload?: boolean;
    // actId 的优先级：action中的 > module中的 > aiTrack中的
    actId?: number | string;
    action: {
        [tag: string]: AitActionData;
    };
}

// 页面PV
export const AitPageLoadedKey = 'aitPageLoaded';
export const AitPageUnLoadedKey = 'aitPageUnLoaded';

export class AitGlobalLogDatas {
    dataMap: Map<string, AitLogData>;
    constructor() {
        this.dataMap = new Map();
    }

    moduleRegisted(module: string) {
        return this.dataMap.has(module);
    }

    actionRegisted(module: string, actionVal: string) {
        let moduleObj = this.dataMap.get(module);
        if (!moduleObj) {
            return false;
        }

        // 遍历对象中是否包含了该value
        let actionObj = moduleObj.action;
        for (const key in actionObj) {
            if (Object.prototype.hasOwnProperty.call(actionObj, key)) {
                const element = (actionObj as any)[key];
                if (element.value === actionVal) {
                    return true;
                }
            }
        }
        return false;
    }

    registerLogData(logData: AitLogData) {
        if (this.dataMap.has(logData.module)) {
            debugerror(aitErrorMessages[AitErrorCodes.DATA_MODULE_EXISTS], logData.module);
            return false;
        }
        this.dataMap.set(logData.module, logData);
        return true;
    }

    registerLogDatas(logDatas: AitLogData[]) {
        logDatas.forEach(data => this.registerLogData(data));
        return true;
    }

    checkDataIsValid(aitLogData: AitLogData, actionObj?: AitActionData) {
        if (!aitLogData) {
            debugerror(aitErrorMessages[AitErrorCodes.DATA_COMPONENT_NULL]);
            return false;
        }

        if (!aitLogData.module) {
            debugerror(aitErrorMessages[AitErrorCodes.DATA_MODULE_NULL], aitLogData);
            return false;
        }

        if (!this.moduleRegisted(aitLogData.module)) {
            debugerror(aitErrorMessages[AitErrorCodes.DATA_MODULE_NOT_REGISTERED], aitLogData.module, aitLogData);
            return false;
        }

        if (!actionObj) {
            debugerror(aitErrorMessages[AitErrorCodes.DATA_ACTION_EMPTY], aitLogData.module);
            return false;
        }

        if (!actionObj.value) {
            debugerror(aitErrorMessages[AitErrorCodes.DATA_ACTION_VALUE_EMPTY], actionObj);
            return false;
        }

        if (!actionObj.behavior) {
            debugerror(aitErrorMessages[AitErrorCodes.DATA_ACTION_BEHAAVIOR_EMPTY], actionObj);
            return false;
        }

        // 如果传 action，必须在配置中定义
        let action = actionObj.value;
        if (!this.actionRegisted(aitLogData.module, action)) {
            debugerror(aitErrorMessages[AitErrorCodes.DATA_ACTION_NOT_REGISTERED], aitLogData.module, action);
            return false;
        }

        return true;
    }
}

