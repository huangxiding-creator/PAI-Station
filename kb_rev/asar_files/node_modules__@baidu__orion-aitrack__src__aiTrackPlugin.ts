import Vue from 'vue';
import {AitLogData, AitActionData, debugerror, AiTrack} from '@baidu/orion-aitrack-common';

export interface AitHTMLElement extends HTMLElement {
    __aitLogData?: AitLogData | null | undefined;
    __timeoutId?: NodeJS.Timeout;
}

export interface AitVueComponent extends Vue {
    aitLogData?: AitLogData;
}

export interface AitrackPluginOptions {
    aiTrack: AiTrack;
}

export default {
    install(vue: typeof Vue, options: AitrackPluginOptions) {
        let aiTrack = options.aiTrack;
        if (!aiTrack) {
            throw Error('aiTrack is required');
        }

        const bindAitDataToElemet = (element: AitHTMLElement, aitLogData: AitLogData, binding: any) => {
            if (!aitLogData) {
                return;
            }
            element.__aitLogData = aitLogData;
            // 绑定module，为了查找点位
            element.setAttribute('data-ait-module', aitLogData.module);
            let actionObj = binding.value;
            if (actionObj?.value) {
                element.setAttribute('data-ait-action', actionObj.value);
            }
        };

        // 通过action进行数据上报
        vue.prototype.$aitLogForAction = function (action: AitActionData, params: Record<string, any>) {
            aiTrack.logForModule(this.aitLogData, action , params);
        };

        vue.prototype.$aitLogForActId = function (actId: number, params: Record<string, any>) {
            aiTrack.logForActId(actId, params);
        };

        vue.prototype.$aitLog = function (action: AitActionData, params: Record<string, any>) {
            aiTrack.log(this.aitLogData, action, params);
        };

        vue.prototype.$aitLogForModule = function (module: AitLogData, action: AitActionData, params: Record<string, any>) {
            aiTrack.logForModule(module, action, params);
        };

        /**
         * 监听组件显示指令, value 是具体的action
         * modifiers 支持如下：
         * viewport: 用户看见才算显示
         * once: 只上报一次
         * muti: 有几次上报几次
         *
         * mounted: 只要挂载上就算
         * v-ait-show.mounted
         * v-ait-show.mounted='vip'
         *
         * v-ait-show.viewport.once: 只上报一次
         * v-ait-show.viewport.muti: 上报多次
         * v-ait-show.viewport.once='vip'
         *
         * value: 值为模块名
         */
        vue.directive('aitShow', {
            // 只调用一次，指令第一次绑定到元素时调用。在这里可以进行一次性的初始化设置。
            bind(element: AitHTMLElement, binding, vnode) {
                if (!window.IntersectionObserver) {
                    // 低版本浏览器不支持 IntersectionObserver（量比较小，可忽略）
                    return;
                }
                let vueComponent = vnode.context as AitVueComponent;
                if (vueComponent) {
                    // bind 的时候给el上绑定数据
                    bindAitDataToElemet(element, vueComponent.aitLogData as AitLogData, binding);
                    let {value} = binding;
                    let observer = new IntersectionObserver(entries => {
                        if (entries[0]?.isIntersecting) {
                            if (!element.__aitLogData) {
                                debugerror(element, entries[0]);
                            }
                            aiTrack.logForModule(element.__aitLogData as AitLogData, value);

                            if (binding.modifiers.once) {
                                observer.disconnect();
                            }
                        }
                    }, {
                        threshold: 0
                    });
                    (element as any).__aitInObserver = observer;
                }
                else {
                    debugerror('aitShow bind vueComponent is null', vnode);
                }
            },

            // 被绑定元素插入父节点时调用 (仅保证父节点存在，但不一定已被插入文档中)
            inserted(element: AitHTMLElement, binding) {
                let {value} = binding;
                let delayTime = value.delay || 0;
                if (binding.modifiers.mounted) {
                    // 元素被挂载时上报
                    element.__timeoutId = setTimeout(() => {
                        // 延迟执行，使用者可以在 mounted 钩子函数中添加自定义参数
                        if (element) {
                            aiTrack.logForModule(element.__aitLogData as AitLogData, value);
                        }
                    }, delayTime);
                }
                else if (binding.modifiers.viewport) {
                    // 元素可见时上报
                    element.__timeoutId = setTimeout(() => {
                        if (element) {
                            let observer =  (element as any).__aitInObserver as IntersectionObserver;
                            observer && observer.observe(element);
                        }
                    }, delayTime);
                }
            },

            // 只调用一次，指令与元素解绑时调用。
            unbind(element: AitHTMLElement, bind) {
                let observer =  (element as any).__aitInObserver as IntersectionObserver;
                if (observer) {
                    observer.disconnect();
                }
                if (element.__timeoutId) {
                    clearTimeout(element.__timeoutId);
                }
            }
        });

        /**
         * 点击指令
         * modifiers 支持如下：
         * once: 只上报一次
         * muti: 有几次上报几次（默认）
         *
         * mounted: 只要挂载上就算
         *
         * v-ait-click.once: 只上报一次
         * v-ait-click.muti: 上报多次
         *
         * value: 值为模块名
         *
         * 事件触发的顺序：
         * 1、如果使用 capture，也就是捕获阶段进行触发事件，先父元素，再子元素，这样有个问题，子父都有绑定事件时会导致同时触发；
         * 2、如果使用 bubble，也就是冒泡阶段进行触发事件，先子元素，再父元素，这样有个问题先触发组件绑定的事件，然后才能触发打点事件；
         */
        vue.directive('aitClick', {
            // 只调用一次，指令第一次绑定到元素时调用。在这里可以进行一次性的初始化设置。
            bind(element: AitHTMLElement, binding, vnode) {
                let vueComponent = vnode.context as AitVueComponent;
                if (vueComponent) {
                    // bind 的时候给el上绑定数据
                    bindAitDataToElemet(element, vueComponent.aitLogData as AitLogData, binding);
                }
                else {
                    debugerror('aitClick bind vueComponent is null', vnode);
                }
            },

            // 指令所在元素被插入页面时
            inserted(element: AitHTMLElement, binding) {
                let value = binding.value as AitActionData;
                const didClick = () => {
                    if (element.__aitLogData) {
                        aiTrack.logForModule(element.__aitLogData, value);
                    }
                    else {
                        debugerror('aitClick didClick, but no aitLogData');
                    }
                };

                let options = {} as any;
                if (binding.modifiers.once) {
                    options = {
                        once: true
                        // capture: true
                    };
                }
                element.addEventListener('click', didClick, options);
            }
        });
    }
};
