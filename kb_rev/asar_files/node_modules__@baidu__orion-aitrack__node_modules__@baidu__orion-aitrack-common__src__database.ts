const DB_VERSION = 1;
const DB_NAMVE = 'AiTrack';
const TABLE_NAME = 'userLog'

export default class AiTrackDB {
    // Hold an instance of a db object for us to store the IndexedDB data in
    db: IDBDatabase | undefined;

    constructor() {
        if (!window.indexedDB) {
            console.log("You broser doesn't support indexedDB to store data!");
            return;
        }
    }

    createDB(): Promise<boolean> {
        return new Promise(resolve => {
            if (this.db) {
                resolve(true);
            }
            if (!window.indexedDB) {
                console.log("You broser doesn't support indexedDB to store data!");
                resolve(false);
                return;
            }
            let dbRequest = indexedDB.open(DB_NAMVE, DB_VERSION);
            dbRequest.onerror = e => {
                resolve(false);
            };
            dbRequest.onsuccess = (e: Event) => {
                this.db = dbRequest.result;
                resolve(true);
            };
            // the database update, should create store
            dbRequest.onupgradeneeded = (e: IDBVersionChangeEvent) => {
                this.db = (e.target as IDBOpenDBRequest).result;

                const userLogStore = this.db.createObjectStore(TABLE_NAME, {
                    autoIncrement: true
                });
                userLogStore.createIndex('actId', 'actId', { unique: false });
                userLogStore.createIndex('module', 'module', { unique: false });
                userLogStore.createIndex('action', 'action', { unique: false });
                userLogStore.createIndex('behavior', 'behavior', { unique: false });
            };
        });
    }

    add(actId: number, params: Record<string, any>) {
        const dataInfo = {
            actId: actId,
            ...params
        };

        const submit = (db: IDBDatabase) => {
            const transaction = db.transaction(TABLE_NAME, 'readwrite');
            const store = transaction.objectStore(TABLE_NAME);
            store.add(dataInfo);
        }

        this.createDB().then(isSuccess => {
            if (isSuccess) {
                submit(this.db as IDBDatabase);
            }
        }).catch(error => {
            console.error(error);
        });
    }
}