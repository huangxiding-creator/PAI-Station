import { isInMini } from './utils';

function getTargetElement(args: any[]) {
    if (!args) {
        return;
    }
    let moduleObj = args.find(item => item.module);
    if (!moduleObj) {
        return;
    }

    let module = moduleObj.module;
    // document.querySelector('[data-ait-module="BarTop"]')
    let targetEl = document.querySelector(`[data-ait-module="${module}"]`);
    return targetEl;
}

function logElement(args: any[]) {
    if ((window as any).__aitlog__ === '2') {
        let el = getTargetElement(args);
        console.log(el);
    }
}

export function debugerror(...args: any[]) {
    if (isInMini()) {
        console.error('[aiTrack] - ', ...args);
        return;
    }

    if ((window as any).__aitlog__) {
        console.error('[aiTrack] - ', ...args);
    }
    logElement(args);
}

export function debug(...args: any[]) {
    if (isInMini()) {
        return;
    }
    if ((window as any).__aitlog__) {
        console.log('[aiTrack] - ', ...args);
    }
    logElement(args);
}
