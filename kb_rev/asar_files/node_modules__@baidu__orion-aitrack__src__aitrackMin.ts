import {
    AitGlobalLogDatas,
    AitLogData, 
    AitActionData,
    debugerror,
    aitErrorMessages,
    AitErrorCodes
} from '@baidu/orion-aitrack-common';
import {LogFunc} from './types/common';

export interface AiTrackMiniOptions {
    actId: number;
    openLog: boolean;
    logCallback: LogFunc;
}

export class AiTrackMini {
    options: AiTrackMiniOptions;
    actId: number;

    private readonly gloablLogDatas: AitGlobalLogDatas;

    constructor(options: AiTrackMiniOptions) {
        this.options = options;
        if (!options.actId) {
            throw new Error(aitErrorMessages[AitErrorCodes.ACTID_EMPTY]);
        }

        this.actId = options.actId;
        this.gloablLogDatas = new AitGlobalLogDatas();
    }

    registerLogData(logData: AitLogData) {
        return this.gloablLogDatas.registerLogData(logData);
    }

    registerLogDatas(logDatas: AitLogData[]) {
        return this.gloablLogDatas.registerLogDatas(logDatas);
    }

    log(
        logData: AitLogData,
        actionData: AitActionData,
        params?: Record<string, any>
    ) {
        if (!this.actId) {
            debugerror(aitErrorMessages[AitErrorCodes.ACTID_EMPTY]);
        }

        const isValid = this.gloablLogDatas.checkDataIsValid(logData, actionData);
        if (!isValid) {
            return;
        }

        const logparams = {
            module: logData.module,
            action: actionData.value,
            aitrack: 1,
            behavior: actionData.behavior
        };

        if (logData.customParams) {
            Object.assign(logparams, logData.customParams);
        }
        if (actionData?.customParams) {
            Object.assign(logparams, actionData.customParams);
        }

        if (params) {
            Object.assign(logparams, params);
        }

        if (this.options.openLog) {
            console.log(this.actId, logparams);
        }

        this.options.logCallback(logparams);
    }
}

