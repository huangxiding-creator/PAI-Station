export function parseQueryString(query: string): Map<string, any> {
    if (!query) {
        return new Map();
    }
    const params = new Map();
    try {
        for (const part of query.split('&')) {
            const param = part.split('=');
            const key = param[0].toLowerCase();
            const value = param.length > 1 ? param[1] : '';
            params.set(decodeURIComponent(key), decodeURIComponent(value));
        }
    } catch (error) {

    }
    return params;
}

export function findRelatedComponent(el: any) {
    while (!el.__vue__ && el.parentElement) {
        el = el.parentElement;
    }
    return el.__vue__;
}

export function getURL(urlString: string): URL | undefined {
    try {
        let urlObj = new URL(urlString);
        return urlObj;
    } catch (error) {
        return;
    }
}

export function getReferrerDomain() {
    let urlObj = getURL(document.referrer);
    return urlObj?.hostname;
}

export function isInMini() {
    if (typeof window != "undefined") {
        return false;
    }
    return true;
};
