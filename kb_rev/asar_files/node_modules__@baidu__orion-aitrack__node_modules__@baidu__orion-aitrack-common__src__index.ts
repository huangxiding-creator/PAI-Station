import {log} from '@baidu/orion-log';
import {parseQueryString} from './utils';
import {debug, debugerror} from './debug';
import {AitGlobalLogDatas, AitLogData, AitActionData, AitPageLoadedKey} from './logData';
import {AitErrorCodes, aitErrorMessages} from './error';
import {aitTrackLogConfig} from './shared';
import AiTrackDB from './database';
import {LogFunc} from './types/common';

export interface AiTrackOptions {
    // 唯一的上报id
    actId: number;
    // 是否使用DB进行日志存储，方便验证点位的正确性
    useDB?: boolean;
    // 自定义打点函数
    logCallback?: LogFunc;
}

export class AiTrack {
    options: AiTrackOptions;
    actId: number;
    // 页面加载时间
    startTime: number = 0;
    // 是否上报了页面停留时长
    uploadedStayTime: boolean = false;
    db?: AiTrackDB | undefined;

    private readonly gloablLogDatas: AitGlobalLogDatas;

    constructor(options: AiTrackOptions) {
        this.options = options;
        if (!options.actId) {
            throw new Error(aitErrorMessages[AitErrorCodes.ACTID_EMPTY]);
        }
        if (options.useDB) {
            this.db = new AiTrackDB();
        }

        /**
         * 点位日志信息，支持的值：
         * 1：Console面板输出每次上报的数据
         * 2：Console面板输出带有DOM节点的日志
        */
        const queryStr = location.search?.split('?')[1];
        if (queryStr) {
            (window as any).__aitlog__ = parseQueryString(queryStr).get('__aitlog__');
        }

        this.actId = options.actId;
        this.startTime = (new Date()).getTime();
        this.gloablLogDatas = new AitGlobalLogDatas();
        // this.addPageLifecycleEvent();
    }

    addPageLifecycleEvent() {
        const queryStr = location.search?.split('?')[1];
        let queryMap: Map<string, any> = new Map();
        if (queryStr) {
            queryMap = parseQueryString(queryStr);
        }

        document.addEventListener('DOMContentLoaded', () => {
            let params: Record<string, any> = {};
            if (queryMap?.has('from')) {
                params.from = queryMap.get('from');
            }
            Object.assign(params, {
                module: aitTrackLogConfig.module,
                action: aitTrackLogConfig.action[AitPageLoadedKey].value,
                behavior: aitTrackLogConfig.action[AitPageLoadedKey].behavior
            });
            this.logForActId(this.actId, params);
        });
    }

    registerLogData(logData: AitLogData) {
        return this.gloablLogDatas.registerLogData(logData);
    }

    registerLogDatas(logDatas: AitLogData[]) {
        return this.gloablLogDatas.registerLogDatas(logDatas);
    }

    logForModule(
        logData: AitLogData,
        actionData: AitActionData,
        params: Record<string, any> = {}
    ) {
        if (!this.actId) {
            debugerror(aitErrorMessages[AitErrorCodes.ACTID_EMPTY]);
        }

        const isValid = this.gloablLogDatas.checkDataIsValid(logData, actionData);
        if (!isValid) {
            return;
        }

        const logparams = {
            module: logData.module,
            action: actionData ? actionData.value : '',
            behavior: actionData?.behavior
        };

        if (logData.customParams) {
            Object.assign(logparams, logData.customParams);
        }
        if (actionData?.customParams) {
            Object.assign(logparams, actionData.customParams);
        }

        if (params) {
            Object.assign(logparams, params);
        }

        this.sendLog(this.actId, logparams);
    }

    log(
        logData: AitLogData,
        actionData: AitActionData,
        params?: Record<string, any>
    ) {
        if (!this.actId) {
            debugerror(aitErrorMessages[AitErrorCodes.ACTID_EMPTY]);
        }

        const isValid = this.gloablLogDatas.checkDataIsValid(logData, actionData);
        if (!isValid) {
            return;
        }

        const logparams = {
            module: logData.module,
            action: actionData.value,
            aitrack: 1,
            behavior: actionData.behavior
        };

        if (logData.customParams) {
            Object.assign(logparams, logData.customParams);
        }
        if (actionData?.customParams) {
            Object.assign(logparams, actionData.customParams);
        }

        if (params) {
            Object.assign(logparams, params);
        }

        this.sendLog(this.actId, logparams);;
    }

    logForActId(actId: number, params: Record<string, any> = {}) {
        if (!actId) {
            debugerror(aitErrorMessages[AitErrorCodes.ACTID_EMPTY]);
            return;
        }

        this.sendLog(actId, params);
    }

    sendLog(actId: number, params: Record<string, any>) {
        params.aitrack = 1;
        debug(actId, params);
        if (this.db) {
            this.db.add(actId, params);
        }

        if (this.options?.logCallback) {
            this.options.logCallback({
                ...params
            });
            return;
        }

        log.xsend(actId, {
            ...params
        });
    }
}