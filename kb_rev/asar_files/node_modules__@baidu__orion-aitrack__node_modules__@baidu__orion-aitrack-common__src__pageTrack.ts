import {
    AitLogData,
    AitActionData
} from './logData';
import {
    getURL
} from './utils';

export interface PageIdInfo {
    [key: string]: {
        url?: string;
        reg?: RegExp;
    }
}

export const WK_WAP_PAGE_MAP: PageIdInfo = {
    aitpage_wapview: {
        // 阅读页
        reg: /\/view\/\w{5,}?/
    },
    aitpage_aggview: {
        // 阅读页
        reg: /\/aggs?\/\w{5,}?/
    },
    aitpage_waptag: {
        // 阅读页
        reg: /\/tag\/\w{5,}?/
    },
    aitpage_waphome: {
        // 首页
        url: '/'
    }
}

export interface ReferOptions {
    // 使用path的域名，比如 wk.baidu.com
    pathDomains?: string[];
    // 要解析的 url，默认为 document.referrer
    url?: string;
    // page配置信息
    pageConfig: PageIdInfo;
};

export function getReferId(options: ReferOptions) {
    let parseUrl = options?.url || document.referrer || '';
    let urlObj = getURL(parseUrl);
    if (urlObj) {
        if (options?.pathDomains) {
            // 需要使用path的域名
            const isUsePath = options.pathDomains.find(item => item === urlObj?.hostname);
            if (isUsePath) {
                // 字符串
                let hitPageId = Object.keys(options.pageConfig).find(pageId => options.pageConfig[pageId].url === urlObj?.pathname);
                if (hitPageId) {
                    return hitPageId;
                }

                // 正则匹配
                let matches;
                hitPageId = Object.keys(options.pageConfig).find(pageId => {
                    let reg = options.pageConfig[pageId]?.reg;
                    if (!reg) {
                        return false;
                    }

                    matches = urlObj?.pathname?.match(reg)
                    if (!matches) {
                        return false
                    }

                    return true
                });
                if (hitPageId) {
                    return hitPageId;
                }

                let pathname = urlObj.pathname;
                if (pathname) {
                    if (pathname.startsWith('/')) {
                        pathname = pathname.substring(1);
                    }
                    return `aitpage_${pathname.replaceAll('/', '_')}`;
                }

                return '';
            }
            else {
                return urlObj.hostname;
            }
        }
    }
    else {
        return ''
    }
}

/**
 * 通过AiTrack中定义的数据获取location（可展示到AiTrack平台上）
 * @param moduleObj AiTrack中定义的module
 * @param actionObj AiTrack中定义的action
 * @returns
 */
 export function getCCodeLocation(moduleObj: AitLogData, actionObj: AitActionData | string) {
    let actionValue = '';
    if (typeof actionObj === 'string') {
        actionValue = actionObj;
    }
    else {
        actionValue = actionObj.value;
    }

    if (!actionObj || !moduleObj.action[actionValue]) {
        console.error('[AiTrack] get ccode error, can not found action', moduleObj, actionObj);
        return '';
    }
    return `${moduleObj.module}.${actionValue}`;
};
