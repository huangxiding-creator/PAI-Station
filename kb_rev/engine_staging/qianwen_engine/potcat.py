# -*- coding: utf-8 -*-
"""锅圈分类标签（v0.9.10 用户令 1009：存量+增量问答按主题打分类标签，便于分类查看）。

读时纯函数分类器：零 schema 迁移、零回填任务——存量与新增走同一函数即打即得；
分类规则升级时全部条目自动重标，无陈旧数据、无迁移风险。
关键词首中即归类（规则顺序=优先级：具体业务词在前，泛词在后），未中 → 其他。
"""

# (分类名, 关键词表) —— 顺序即匹配优先级
CATEGORY_RULES: tuple = (
    ("索赔与变更", ("索赔", "反索赔", "变更", "签证", "赶工", "窝工", "停工损失",
                    "费用补偿", "工期延误费")),
    ("付款与背靠背", ("背靠背", "付款", "进度款", "工程款", "拖欠", "逾期支付",
                      "利息", "质保金", "履约保证金", "预付款")),
    ("结算与审计", ("结算", "审计", "决算", "对账")),
    ("计价与调价", ("计价", "调价", "固定总价", "材料价", "信息价", "涨价",
                    "单价", "概算", "预算", "工程量清单", "清单")),
    ("招投标与联合体", ("招标", "投标", "中标", "废标", "联合体", "串通",
                        "围标", "评标", "不平衡报价", "资质")),
    ("工期与质量", ("工期", "进度计划", "进度", "开工", "竣工", "验收",
                    "质量", "缺陷", "保修", "返工", "试运行")),
)

FALLBACK_CATEGORY = "其他"


def classify(question: str) -> str:
    """问题文本 → 分类名。纯函数无副作用：空文本/无命中 → 其他。"""
    text = question or ""
    for name, keywords in CATEGORY_RULES:
        for kw in keywords:
            if kw and kw in text:
                return name
    return FALLBACK_CATEGORY
