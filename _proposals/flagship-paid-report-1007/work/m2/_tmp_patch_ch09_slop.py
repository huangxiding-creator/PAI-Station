print(f"table_rows={len(t0)} changed_rows={len(changed)}")
for a, b in changed: print("  TABLE:", a[:30], "=>", b[:30])
if len(t0) != len(t1) or len(changed) > 5:
    print("TABLE MISMATCH"); sys.exit(1)

