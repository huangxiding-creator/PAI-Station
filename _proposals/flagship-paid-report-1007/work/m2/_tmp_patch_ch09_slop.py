# 完整性: 数字多重集不变
d0 = collections.Counter(re.findall(r"\d+", orig))
d1 = collections.Counter(re.findall(r"\d+", text))
if d0 != d1:
    diff = {k: (d0.get(k, 0), d1.get(k, 0)) for k in set(d0) | set(d1) if d0.get(k, 0) != d1.get(k, 0)}
    print("DIGIT MISMATCH:", diff); sys.exit(1)
# P锚点序列不变
p0 = re.findall(r"P\d{6}", orig); p1 = re.findall(r"P\d{6}", text)
if p0 != p1:
    print("ANCHOR MISMATCH"); sys.exit(1)
# 标题行不变
h0 = [l for l in orig.split("\n") if l.startswith("#")]
h1 = [l for l in text.split("\n") if l.startswith("#")]
if h0 != h1:
    print("HEADING MISMATCH"); sys.exit(1)
# 表格行: 除5条白名单行外逐字节不变
t0 = [l for l in orig.split("\n") if l.startswith("|")]
t1 = [l for l in text.split("\n") if l.startswith("|")]
