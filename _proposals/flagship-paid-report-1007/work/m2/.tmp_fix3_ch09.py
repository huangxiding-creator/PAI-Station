def replace_section(text, header_prefix, new_body):
    parts = re.split(r'(?m)(?=^## )', text)
    out = []
    nl = chr(10)
    for p in parts:
        if p.startswith('## ') and p.split(nl)[0].strip('# ').split()[0] == header_prefix:
            out.append(new_body)
        else:
            out.append(p)
    return ''.join(out)


