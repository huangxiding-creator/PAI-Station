# -*- coding: utf-8 -*-
import io

def patch(fn, pairs):
    t = io.open(fn, encoding='utf-8').read()
    for old, add in pairs:
        assert old in t, (fn, old[:40])
        t = t.replace(old, old + add, 1)
    io.open(fn, 'w', encoding='utf-8').write(t)

