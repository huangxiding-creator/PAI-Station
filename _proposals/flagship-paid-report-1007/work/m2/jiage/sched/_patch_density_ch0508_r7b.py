def digits(t): return collections.Counter(re.findall(r"\d[\d.,%/－—~\-]*\d|\d", t))
def anchors(t): return re.findall(r"\[来源:\s*(?:P\d{6}[,，;\s]*)+\]", t)
def dup(t):
    return sum(v-1 for v in collections.Counter(l.strip() for l in t.splitlines() if len(l.strip())>=30).values() if v>1)

def ins_after(t, anchor, para):
    assert t.count(anchor) == 1, f"anchor x{t.count(anchor)}: {anchor[:30]}"
    return t.replace(anchor, anchor + "\n\n" + para)

def del_para_containing(t, key):
    paras = t.split('\n\n')
    hit = [i for i,p in enumerate(paras) if key in p]
    assert len(hit) == 1, f"del key x{len(hit)}: {key}"
    del paras[hit[0]]
    return '\n\n'.join(paras)

def finish(path, t0, t):
    d0, d1 = digits(t0), digits(t)
    assert all(d1[k] <= d0.get(k, 0) for k in d1), path + " digits 新增!"
    assert set(anchors(t)) <= set(anchors(t0)), path + " anchors 新增!"
    assert dup(t) == 0, f"{path} dup={dup(t)}"
    m = metrics(t); assert m['slop_hits'] == 0
    cjk = len(re.findall(r"[一-鿿]", t))
    t = re.sub(r"<!-- chars: \d+ -->", f"<!-- chars: {cjk} -->", t)
    open(path, 'w', encoding='utf-8', newline='\n').write(t)
    print(f"{path}: rate={m['new_ngram_rate']} redund={m['redundancy_ratio']} slop={m['slop_hits']} cjk={m['cjk_chars']}")

