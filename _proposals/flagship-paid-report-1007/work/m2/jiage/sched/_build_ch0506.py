CITE_RE = re.compile(r"\[(\d{1,3}(?:\s*[-,，]\s*\d{1,3})*)\]")


def cite_to_map(text: str, mapping: dict[int, str]):
    """[N]/[N, M]/[N-M] -> [来源: P...]; 幽灵(无对应源)剔除; 全幽灵组整体删除."""
    ghosts: set[int] = set()
    used: set[int] = set()

    def repl(m: re.Match) -> str:
        body = m.group(1)
        nums: list[int] = []
        for it in re.split(r"[,，]", body):
            it = it.strip()
            if not it:
                continue
            if "-" in it:
                a, b = it.split("-", 1)
                try:
                    nums.extend(range(int(a), int(b) + 1))
                except ValueError:
                    pass
            else:
                nums.append(int(it))
        keep = []
        for n in nums:
            if n in mapping:
                keep.append(n)
                used.add(n)
            else:
                ghosts.add(n)
        if not keep:
            return ""
        anchors = ", ".join(mapping[n] for n in sorted(set(keep)))
        return f"[来源: {anchors}]"

    out = CITE_RE.sub(repl, text)
    return out, len(used), len(ghosts)


def drop_ascii(text: str) -> tuple[str, int]:
    """ASCII 流程图整块删除(体裁纪律+dup手术源)."""
    out, n = re.subn(r"```[\s\S]*?```\n?", "", text)
    return re.sub(r"\n{3,}", "\n\n", out), n


def strip_line_noise(text: str) -> str:
    text = re.sub(r"(?m)^💡 .*$\n?", "", text)
    text = re.sub(r"(?m)^【未写小节清单】[：:][^\n]*$", "", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return re.sub(r"(?m)^---\s*\n+---\s*$", "---", text, flags=re.M)


def endnote_table(text: str, titles: dict[str, str]) -> str:
    used = sorted(set(re.findall(r"P\d{6}", text)))
    rows = ["| 事实锚 | 源文（事实资料库实收件） |", "| :--- | :--- |"]
    for p in used:
        rows.append(f"| {p} | {titles.get(p, '（待核）')} |")
    return "\n".join(rows) + "\n"


