def dupcheck(name: str) -> None:
    t = read(name)
    from collections import Counter
    keep, inf = [], False
    for l in t.splitlines():
        if l.strip().startswith("```"):
            inf = not inf
            continue
        if not inf and len(l.strip()) >= 30:
            keep.append(l.strip())
    dupp = sum(v - 1 for v in Counter(keep).values() if v > 1)
    heads = [l.strip() for l in t.split("\n") if re.match(r"^#{1,4}\s+\S", l.strip())]
    duph = sum(v - 1 for v in Counter(heads).values() if v > 1)
    ai = bool(re.search(r"AI|人工智能|大模型|GPT|Claude|NotebookLM|机器生成|算法", t))
    print(f"[dupcheck] {name}: dup段{dupp} dup题{duph} AI/生成式提及={ai} | 标题数{len(heads)} | CJK {cjk(t):,}")


