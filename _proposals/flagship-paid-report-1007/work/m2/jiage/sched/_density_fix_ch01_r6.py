# ---------- 程序化域词轮换 (豁免: 表格行/标题行/定义首现/引号条文) ----------
def rotate_term(text, term, synonyms, skip_first=True, protected_extra=()):
    """在非表格/非标题/非首个定义处的 prose 中轮换 term → synonyms 循环."""
    lines = text.split('\n')
    seen = 0
    out = []
    syn_i = 0
    for ln in lines:
        s = ln.lstrip()
        if (s.startswith('|') or s.startswith('#') or s.startswith('```')
                or s.startswith('> ') or any(p in ln for p in protected_extra)):
            out.append(ln); continue
        idx = 0
        while term in ln[idx:]:
            pos = ln.index(term, idx)
            seen += 1
            if skip_first and seen == 1:
                idx = pos + len(term); continue
            # 引号内条文豁免: 该出现前后60字符内有 '定义' '释义' '规定：' 则跳过
            ctx = ln[max(0,pos-40):pos+60]
            if any(k in ctx for k in ('定义为', '释义', '明确为', '规定：', '明确：', '界定为', '划定为', '写道：', '写明“', '明确“', '约定：“')):
                idx = pos + len(term); continue
            syn = synonyms[syn_i % len(synonyms)]
            syn_i += 1
            ln = ln[:pos] + syn + ln[pos+len(term):]
            idx = pos + len(syn)
        out.append(ln)
    return '\n'.join(out)

