CITE_RE = re.compile(r"\[(\d{1,3}(?:\s*[-,，]\s*\d{1,3})*)\]")


def cite_to_map(text: str, mapping: dict[int, str]):
    """[N]/[N, M]/[N-M] -> [来源: P...]; 幽灵(无对应源)剔除; 全幽灵组整体删除."""
    ghosts: set[int] = set()
    used: set[int] = set()

    def repl(m: re.Match) -> str:
        body = m.group(1)
        nums: list[int] = []
        for it in re.split(r"[,，]", body):
            it = it.strip()
            if not it:
                continue
            if "-" in it:
                a, b = it.split("-", 1)
                try:
                    nums.extend(range(int(a), int(b) + 1))
                except ValueError:
                    pass
            else:
                nums.append(int(it))
        keep = []
        for n in nums:
            if n in mapping:
                keep.append(n)
                used.add(n)
            else:
                ghosts.add(n)
        if not keep:
            return ""
        anchors = ", ".join(mapping[n] for n in sorted(set(keep)))
        return f"[来源: {anchors}]"

    out = CITE_RE.sub(repl, text)
    return out, len(used), len(ghosts)


def strip_residue(text: str) -> str:
    """聊天残留: 未写小节清单 / 💡行 / 源引用对照节(尾注自动重建)."""
    text = re.sub(r"(?m)^【未写小节清单】[：:][^\n]*(\n\s*[·\-—].*)*", "", text)
    text = re.sub(r"(?m)^💡 .*$\n?", "", text)
    text = re.sub(r"(?ms)^###? ?《?源引用对照》?(清单)?[\s\S]*?(?=^### 本章术语速查)", "", text)
    return re.sub(r"\n{3,}", "\n\n", text)


def unfence(text: str) -> tuple[str, int, int]:
    """fenced块手术: 纯ASCII流程图已另行整删; 其余块拆围栏保prose, 边框线删除, |标题|转粗体."""
    out, n_unfence, n_border = [], 0, 0
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        if lines[i].strip().startswith("```"):
            j = i + 1
            block = []
            while j < len(lines) and not lines[j].strip().startswith("```"):
                block.append(lines[j])
                j += 1
            n_unfence += 1
            for ln in block:
                s = ln.rstrip()
                if re.match(r"^\s*\+-{2,}\+\s*$", s):          # +----+ 边框
                    n_border += 1
                    continue
                m = re.match(r"^\s*\|(.*?)\|\s*$", s)          # | 标题 |
                if m:
                    inner = m.group(1).strip()
                    if inner:
                        out.append(f"**{inner}**")
                    continue
                out.append(ln)
            i = j + 1
        else:
            out.append(lines[i])
            i += 1
    return re.sub(r"\n{3,}", "\n\n", "\n".join(out)), n_unfence, n_border


def endnote_table(text: str, titles: dict[str, str]) -> str:
    used = sorted(set(re.findall(r"P\d{6}", text)))
    rows = ["| 事实锚 | 源文（事实资料库实收件） |", "| :--- | :--- |"]
    for p in used:
        rows.append(f"| {p} | {titles.get(p, '（待核）')} |")
    return "\n".join(rows) + "\n"


