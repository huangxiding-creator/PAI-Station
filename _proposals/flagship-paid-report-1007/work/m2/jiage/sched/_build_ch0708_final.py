def strip_traces(text: str) -> str:
    for pat in [r"(?m)^【未写小节清单】[：:].*?(?=^#{1,3} |\Z)",
                r"(?m)^《[^》]*》第\d+章[^。]*已在前(两|述各期)次?输出(中|中完整撰写)?[^。]*。.*?(?=^#{1,3} |\Z)"]:
        text = re.sub(pat, "", text, flags=re.S)
    text = re.sub(r"(?m)^· .+$\n?", "", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip() + "\n"


def drop_ascii(text: str) -> tuple[str, int]:
    out, n = re.subn(r"```[\s\S]*?```\n?", "", text)
    return re.sub(r"\n{3,}", "\n\n", out), n


CITE_RE = re.compile(r"\[(\d{1,3}(?:\s*[-,，]\s*\d{1,3})*)\]")


def cite_map(text: str, mapper, valid: set[int]) -> tuple[str, int, int]:
    """[N]→[来源: P锚] 全转换; mapper(n)->锚号字符串; n不在valid=幽灵剔除."""
    ghosts: set[int] = set()
    used: set[int] = set()

    def repl(m: re.Match) -> str:
        nums: list[int] = []
        for it in re.split(r"[,，]", m.group(1)):
            it = it.strip()
            if not it:
                continue
            if "-" in it:
                a, b = it.split("-", 1)
                try:
                    nums.extend(range(int(a), int(b) + 1))
                except ValueError:
                    pass
            else:
                nums.append(int(it))
        keep = []
        for n in nums:
            if n in valid:
                keep.append(n)
                used.add(n)
            else:
                ghosts.add(n)
        if not keep:
            return ""
        anchors = ", ".join(mapper(n) for n in sorted(set(keep)))
        return f"[来源: {anchors}]"

    out = CITE_RE.sub(repl, text)
    return out, len(used), len(ghosts)


def endnote_table(text: str, titles: dict[str, str]) -> str:
    used = sorted(set(re.findall(r"P\d{6}", text)))
    rows = ["| 事实锚 | 源文（事实资料库实收件） |", "| :--- | :--- |"]
    for p in used:
        rows.append(f"| {p} | {titles.get(p, '（待核）')} |")
    return "\n".join(rows) + "\n"


