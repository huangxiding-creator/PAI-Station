def sections(text: str) -> dict[str, str]:
    out: dict[str, str] = {}
    parts = re.split(r"(?m)^(#{2,3} .+)$", text)
    for i in range(1, len(parts) - 1, 2):
        out[parts[i].strip()] = parts[i + 1]
    return out


def pick(sec: dict[str, str], key_sub: str) -> str:
    for k, v in sec.items():
        if key_sub in k:
            return v.rstrip() + "\n"
    raise KeyError(key_sub)


def must(text: str, old: str, new: str, tag: str) -> str:
    """带断言的替换: 锚点未命中即抛错, 杜绝静默漏织."""
    if old not in text:
        raise AssertionError(f"[must] 锚点未命中: {tag}\n锚点头部: {old[:90]!r}")
    return text.replace(old, new, 1)


CITE_RE = re.compile(r"\[(\d{1,3}(?:\s*[-,，]\s*\d{1,3})*)\]")


def cite_to_anchor(text: str, base: int, max_src: int = 20) -> tuple[str, int, int]:
    ghosts = set()
    used: set[int] = set()

    def repl(m: re.Match) -> str:
        nums: list[int] = []
        for it in re.split(r"[,，]", m.group(1)):
            it = it.strip()
            if not it:
                continue
            if "-" in it:
                a, b = it.split("-", 1)
                try:
                    nums.extend(range(int(a), int(b) + 1))
                except ValueError:
                    pass
            else:
                nums.append(int(it))
        keep = []
        for n in nums:
            if 1 <= n <= max_src:
                keep.append(n)
                used.add(n)
            else:
                ghosts.add(n)
        if not keep:
            return ""
        anchors = ", ".join(f"P{base + n:06d}" for n in sorted(set(keep)))
        return f"[来源: {anchors}]"

    out = CITE_RE.sub(repl, text)
    return out, len(used), len(ghosts)


def strip_traces(text: str) -> str:
    for pat in [r"(?m)^【未写小节清单】[：:].*?(?=^#{1,3} |\Z)",
                r"(?m)^《[^》]*》第\d+章[^。]*已在前(两|述各期)次?输出(中|中完整撰写)?[^。]*。.*?(?=^#{1,3} |\Z)"]:
        text = re.sub(pat, "", text, flags=re.S)
    text = re.sub(r"(?m)^· .+$\n?", "", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip() + "\n"


def drop_ascii(text: str) -> tuple[str, int]:
    out, n = re.subn(r"```[\s\S]*?```\n?", "", text)
    return re.sub(r"\n{3,}", "\n\n", out), n


def endnote_table(text: str, titles: dict[str, str]) -> str:
    used = sorted(set(re.findall(r"P\d{6}", text)))
    rows = ["| 事实锚 | 源文（事实资料库实收件） |", "| :--- | :--- |"]
    for p in used:
        rows.append(f"| {p} | {titles.get(p, '（待核）')} |")
    return "\n".join(rows) + "\n"


