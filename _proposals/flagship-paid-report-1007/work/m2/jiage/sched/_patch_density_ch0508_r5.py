def apply(path, REPL, INS, update_tail):
    t = open(path, encoding="utf-8").read()
    for old, new in REPL:
        c = t.count(old); assert c == 1, f"{path} REPL count={c}: {old[:36]}..."
        t = t.replace(old, new)
    for anchor, add in INS:
        c = t.count(anchor); assert c == 1, f"{path} INS anchor count={c}: {anchor[:36]}..."
        t = t.replace(anchor, anchor + add)
    if update_tail:
        cjk = len(re.findall(r"[一-鿿]", t))
        t = re.sub(r"<!-- chars: \d+ -->", f"<!-- chars: {cjk} -->", t)
    open(path, "w", encoding="utf-8", newline="\n").write(t)
    m = metrics(t)
    print(f"{path}: cjk={m['cjk_chars']} rate={m['new_ngram_rate']} redund={m['redundancy_ratio']} slop={m['slop_hits']}")

