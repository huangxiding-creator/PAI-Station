def digits(s):
    return sorted(re.findall(r'\d+(?:\.\d+)?', s))

a0 = sorted(re.findall(r'\[来源[：:][^\]]*\]', t))
d0 = digits(t)
for i, (o, n) in enumerate(PAIRS, 1):
    c = t.count(o)
    assert c == 1, f'P{i} count={c}: {o[:36]}...'
    assert digits(o) == digits(n), f'P{i} digit mismatch'
    t = t.replace(o, n, 1)

assert sorted(re.findall(r'\[来源[：:][^\]]*\]', t)) == a0, 'anchors changed!'
assert digits(t) == d0, 'digits changed!'
assert [l for l in orig.split('\n') if l.lstrip().startswith('#')] == [l for l in t.split('\n') if l.lstrip().startswith('#')]
assert [l for l in orig.split('\n') if l.lstrip().startswith('|')] == [l for l in t.split('\n') if l.lstrip().startswith('|')]

m = dg.metrics(t)
slop = sum(len(re.findall(pat, t)) for _, pat in dg.SLOP_PATTERNS)
print(f'cjk={m["cjk_chars"]} redundancy={m["redundancy_ratio"]} ngram={m["new_ngram_rate"]} slop={slop}')
t = re.sub(r'<!-- chars: \d+ -->', f'<!-- chars: {m["cjk_chars"]} -->', t)
P.write_text(t, encoding='utf-8')
