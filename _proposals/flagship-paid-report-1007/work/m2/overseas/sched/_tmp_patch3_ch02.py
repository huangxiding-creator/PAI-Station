def digits(s):
    return sorted(re.findall(r'\d+(?:\.\d+)?', s))

a0 = sorted(re.findall(r'\[来源[：:][^\]]*\]', t))
for i, (o, n, mode) in enumerate(PAIRS, 1):
    c = t.count(o)
    assert c == 1, f'P{i} count={c}: {o[:36]}...'
    if mode == 'eq':
        assert digits(o) == digits(n), f'P{i} digit mismatch'
    else:
        assert all(x in digits(n) for x in digits(o)), f'P{i} ins lost digits'
    t = t.replace(o, n, 1)

