def digits(s):
    return sorted(re.findall(r'\d+(?:\.\d+)?', s))

def anchors(s):
    return sorted(re.findall(r'\[来源[：:][^\]]*\]', s))

a0, d0 = anchors(t), digits(t)
for i, (o, n) in enumerate(PAIRS, 1):
    c = t.count(o)
    assert c == 1, f'P{i} count={c}: {o[:40]}...'
    assert digits(o) == digits(n), f'P{i} digit mismatch'
    t = t.replace(o, n, 1)

assert anchors(t) == a0, 'anchors changed!'
assert digits(t) == d0, 'whole-file digits changed!'
heads0 = [l for l in orig.split('\n') if l.lstrip().startswith('#')]
heads1 = [l for l in t.split('\n') if l.lstrip().startswith('#')]
assert heads0 == heads1, 'headings changed!'
tabs0 = [l for l in orig.split('\n') if l.lstrip().startswith('|')]
tabs1 = [l for l in t.split('\n') if l.lstrip().startswith('|')]
assert tabs0 == tabs1, 'tables changed!'

m = dg.metrics(t)
slop = sum(len(re.findall(pat, t)) for _, pat in dg.SLOP_PATTERNS)
