def digits(s):
    return sorted(re.findall(r'\d+(?:\.\d+)?', s))

a0 = sorted(re.findall(r'\[来源[：:][^\]]*\]', t))
for i, item in enumerate(PAIRS, 1):
    o, n, mode = (item + ('eq',)) if len(item) == 2 else item
    c = t.count(o)
    assert c == 1, f'P{i} count={c}: {o[:36]}...'
    if mode == 'eq':
        assert digits(o) == digits(n), f'P{i} digit mismatch'
    else:
        assert all(x in digits(n) for x in digits(o)), f'P{i} ins lost digits'
    t = t.replace(o, n, 1)

a1 = sorted(re.findall(r'\[来源[：:][^\]]*\]', t))
assert all(x in a1 for x in a0), 'old anchor lost!'
assert [l for l in orig.split('\n') if l.lstrip().startswith('#')] == [l for l in t.split('\n') if l.lstrip().startswith('#')]
assert [l for l in orig.split('\n') if l.lstrip().startswith('|')] == [l for l in t.split('\n') if l.lstrip().startswith('|')]

