SPEC = {"engine": "europe_pmc_rest_api", "source": "Europe PMC REST API (search)",
        "note": "A级·学术专利·免登录API; batch1025实装: GET JSON query/pageSize+resultType=core"}


def endpoint(query, rows):
    return ("https://www.ebi.ac.uk/europepmc/webservices/rest/search",
            {"query": query, "format": "json", "pageSize": str(rows),
             "resultType": "core"}, {}, "GET", None)


def extract(data):
    res = ((data or {}).get("resultList") or {}).get("result") or []
    hits = []
    for p in res:
        pid = p.get("id") or ""
        url = ("https://europepmc.org/article/%s/%s"
               % (p.get("source") or "", pid)) if pid else ""
        hits.append({
            "title": p.get("title") or "(无题)",
            "url": url,
            "meta": [m for m in [str(p.get("pubYear") or ""),
                                 p.get("journalTitle") or "",
                                 p.get("doi") or ""] if m],
            "excerpt": (p.get("abstractText") or "")[:1500],
        })
    return hits


if __name__ == "__main__":
    raise SystemExit(core.run(SPEC))

