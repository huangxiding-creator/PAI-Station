from __future__ import annotations

import re
import sys
from pathlib import Path
from urllib.parse import unquote

sys.path.insert(0, str(Path(__file__).resolve().parent))
import http_api_leg_core as core

SPEC = {"engine": "ddgs_duckduckgo_search", "source": "DuckDuckGo html 端点 (ddgs 换代同面)",
        "note": "A级·通用网研·免登录API封装; batch1025实装: GET HTML regex q (result__a/snippet)"}


def endpoint(query, rows):
    return ("https://html.duckduckgo.com/html/",
            {"q": query}, {}, "GET", None)


def extract(data):
    if not isinstance(data, str):
        return []
    snips = [re.sub(r"<[^>]+>", " ", s.group(1)).strip()
             for s in re.finditer(
                 r'class="result__snippet"[^>]*>(.*?)</a>', data, re.S)]
    hits, seen = [], set()
    for i, m in enumerate(re.finditer(
            r'class="result__a"[^>]*href="([^"]+)"[^>]*>(.*?)</a>',
            data, re.S)):
        url = m.group(1)
        mu = re.search(r"[?&]uddg=([^&\"]+)", url)
        if mu:
            url = unquote(mu.group(1))
        if url in seen or "duckduckgo.com" in url:
            continue
        seen.add(url)
        title = re.sub(r"<[^>]+>", "", m.group(2)).strip()
        if not title:
            continue
        snip = snips[i] if i < len(snips) else ""
        hits.append({
            "title": title,
            "url": url,
            "meta": ["DDG html面"],
            "excerpt": (snip or
                        "DuckDuckGo html 面命中: %s" % title)[:1500],
        })
    return hits


if __name__ == "__main__":
    raise SystemExit(core.run(SPEC))

