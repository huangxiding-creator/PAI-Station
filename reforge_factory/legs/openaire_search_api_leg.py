def endpoint(query, rows):
    return ("https://api.openaire.eu/search/publications",
            {"keywords": query, "size": str(rows), "format": "json"},
            {}, "GET", None)


def extract(data):
    hits = []

    def _walk(node):
        out = []
        if isinstance(node, dict):
            t = node.get("title")
            if isinstance(t, dict):
                t = t.get("$")
            if isinstance(t, str) and t.strip():
                out.append((t.strip(), node))
            for v in node.values():
                out += _walk(v)
        elif isinstance(node, list):
            for v in node:
                out += _walk(v)
        return out

    for t, d in _walk(data if isinstance(data, dict) else {}):
        hits.append({
            "title": t or "(无题)",
            "url": str(d.get("url") or d.get("webresourceurl") or ""),
            "meta": [str(d.get("dateofacceptance") or ""),
                     str(d.get("publisher") or "")],
            "excerpt": "OpenAIRE 出版物命中: %s (嵌套JSON形态, "
                       "解析面待实测校准)" % t,
        })
    return hits


if __name__ == "__main__":
    raise SystemExit(core.run(SPEC))

