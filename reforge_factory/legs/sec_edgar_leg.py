SPEC = {"engine": "sec_edgar", "source": "SEC EDGAR 全文检索 (efts search-index)",
        "note": "A级·通用网研·免登录API(全文检索+submissions JSON, 需声明UA, 实测200); batch1025实装: GET JSON q (UA声明在芯)"}


def endpoint(query, rows):
    return ("https://efts.sec.gov/LATEST/search-index",
            {"q": query}, {}, "GET", None)


def extract(data):
    d = data if isinstance(data, dict) else {}
    hits = []
    for h in (((d.get("hits") or {}).get("hits")) or []):
        s = h.get("_source") or {}
        names = ", ".join(s.get("display_names") or [])
        ciks = s.get("ciks") or []
        idr = str(h.get("_id") or "")
        acc, fname = (idr.split(":", 1) + [""])[:2]
        url = ""
        if ciks and acc:
            url = ("https://www.sec.gov/Archives/edgar/data/%s/%s/%s"
                   % (str(ciks[0]).zfill(10),
                      acc.replace("-", ""), fname))
        hits.append({
            "title": "SEC EDGAR 全文命中: %s (%s)"
                     % (names, s.get("file_type") or ""),
            "url": url,
            "meta": [m for m in [names, s.get("file_date") or "",
                                 s.get("file_type") or ""] if m],
            "excerpt": "EDGAR FTS 命中: %s | 表单 %s | 日期 %s | CIK %s"
                       % (names, s.get("file_type") or "-",
                          s.get("file_date") or "-", ciks[:1]),
        })
    return hits


if __name__ == "__main__":
    raise SystemExit(core.run(SPEC))

