from __future__ import annotations

import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import http_api_leg_core as core

SPEC = {"engine": "arxiv_api", "source": "arXiv API (Atom query)",
        "note": "A级·学术专利·免登录API; batch1025实装: GET Atom XML search_query/max_results"}


def endpoint(query, rows):
    return ("https://export.arxiv.org/api/query",
            {"search_query": "all:%s" % query, "start": "0",
             "max_results": str(rows)}, {}, "GET", None)


def extract(data):
    if not isinstance(data, str):
        return []
    try:
        root = ET.fromstring(data)
    except ET.ParseError:
        return []
    ns = {"a": "http://www.w3.org/2005/Atom"}
    hits = []
    for e in root.findall("a:entry", ns):
        title = re.sub(r"\s+", " ", e.findtext("a:title", "", ns)).strip()
        url = e.findtext("a:id", "", ns)
        for l in e.findall("a:link", ns):
            if l.get("type") == "application/pdf":
                url = l.get("href") or url
        auth = e.find("a:author/a:name", ns)
        hits.append({
            "title": title or "(无题)",
            "url": url,
            "meta": [m for m in [e.findtext("a:published", "", ns)[:10],
                                 (auth.text or "").strip()
                                 if auth is not None else ""]
                     if m],
            "excerpt": re.sub(r"\s+", " ",
                              e.findtext("a:summary", "", ns))[:1500],
        })
    return hits


if __name__ == "__main__":
    raise SystemExit(core.run(SPEC))

