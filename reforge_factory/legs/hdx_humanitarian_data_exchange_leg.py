SPEC = {"engine": "hdx_humanitarian_data_exchange", "source": "HDX CKAN package_search",
        "note": "A级·项目数据/数据集·免登录API+数据集; batch1025实装: GET CKAN JSON q/rows"}


def endpoint(query, rows):
    return ("https://data.humdata.org/api/3/action/package_search",
            {"q": query, "rows": str(rows)}, {}, "GET", None)


def extract(data):
    res = ((data or {}).get("result") or {})
    hits = []
    for d in (res.get("results") or []):
        org = d.get("organization") or {}
        hits.append({
            "title": d.get("title") or d.get("name") or "(无题)",
            "url": d.get("url") or
                   ("https://data.humdata.org/dataset/"
                    + str(d.get("name") or "")),
            "meta": [m for m in [org.get("title") or org.get("name") or "",
                                 ", ".join(t.get("display_name", "")
                                           for t in
                                           (d.get("tags") or [])[:4])] if m],
            "excerpt": re.sub(r"<[^>]+>", " ",
                              d.get("notes") or "")[:1500],
        })
    return hits


if __name__ == "__main__":
    raise SystemExit(core.run(SPEC))

