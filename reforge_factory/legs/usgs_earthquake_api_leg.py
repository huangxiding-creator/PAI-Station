SPEC = {"engine": "usgs_earthquake_api", "source": "USGS FDSN event query (geojson)",
        "note": "A级·项目数据/数据集·免登录API; batch1025半实装(形态待实测校准): GET geojson limit/orderby (时间面)"}


def endpoint(query, rows):
    # FDSN 无文本检索参数 — query 仅入台账, 面按最新时间序取事件样本
    return ("https://earthquake.usgs.gov/fdsnws/event/1/query",
            {"format": "geojson", "limit": str(rows), "orderby": "time"},
            {}, "GET", None)


def extract(data):
    hits = []
    for f in ((data or {}).get("features") or []):
        p = f.get("properties") or {}
        co = (f.get("geometry") or {}).get("coordinates") or ["", "", ""]
        mag, place = p.get("mag"), (p.get("place") or "")
        hits.append({
            "title": "M%s %s" % (mag, place),
            "url": p.get("url") or "",
            "meta": [m for m in ["M%s级" % mag, place,
                                 "%s,%s" % (co[1], co[0])] if m],
            "excerpt": "USGS 地震事件: M%s %s — 坐标(%s, %s) 深度%skm "
                       "(FDSN 时间面, 无文本q)"
                       % (mag, place, co[1], co[0], co[2]),
        })
    return hits


if __name__ == "__main__":
    raise SystemExit(core.run(SPEC))

