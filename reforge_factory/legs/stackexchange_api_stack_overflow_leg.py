def endpoint(query, rows):
    return ("https://api.stackexchange.com/2.3/search/advanced",
            {"order": "desc", "sort": "relevance", "q": query,
             "site": "stackoverflow", "pagesize": str(rows),
             "filter": "withbody"}, {}, "GET", None)


def extract(data):
    hits = []
    for it in ((data or {}).get("items") or []):
        hits.append({
            "title": it.get("title") or "(无题)",
            "url": it.get("link") or "",
            "meta": [m for m in ["%s分" % it.get("score"),
                                 "%s答" % it.get("answer_count"),
                                 (it.get("tags") or [""])[0]] if m],
            "excerpt": re.sub(r"<[^>]+>", " ",
                              it.get("body") or "")[:1500],
        })
    return hits


if __name__ == "__main__":
    raise SystemExit(core.run(SPEC))

