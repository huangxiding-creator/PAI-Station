from __future__ import annotations

import sys
from pathlib import Path
from urllib.parse import quote

sys.path.insert(0, str(Path(__file__).resolve().parent))
import http_api_leg_core as core

SPEC = {"engine": "doaj_api", "source": "DOAJ API (search articles)",
        "note": "A级·学术专利·免登录API; batch1025实装: GET JSON path参query+pageSize"}


def endpoint(query, rows):
    return ("https://doaj.org/api/search/articles/" + quote(query, safe=""),
            {"pageSize": str(rows)}, {}, "GET", None)


def extract(data):
    hits = []
    for r in ((data or {}).get("results") or []):
        b = r.get("bibjson") or {}
        link = ""
        for l in (b.get("link") or []):
            if l.get("url"):
                link = l["url"]
                break
        hits.append({
            "title": b.get("title") or "(无题)",
            "url": link or
                   ("https://doaj.org/article/" + str(r.get("id") or "")),
            "meta": [m for m in [str(b.get("year") or ""),
                                 (b.get("journal") or {}).get("title") or "",
                                 ", ".join(a.get("name", "")
                                           for a in
                                           (b.get("author") or [])[:3])]
                     if m],
            "excerpt": (b.get("abstract") or "")[:1500],
        })
    return hits


if __name__ == "__main__":
    raise SystemExit(core.run(SPEC))

