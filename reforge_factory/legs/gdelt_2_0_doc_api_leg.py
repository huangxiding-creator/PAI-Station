SPEC = {"engine": "gdelt_2_0_doc_api", "source": "GDELT 2.0 DOC API (ArtList)",
        "note": "A级·新闻舆情·免登录API; batch1025实装: GET JSON query/mode=ArtList/maxrecords"}


def endpoint(query, rows):
    return ("https://api.gdeltproject.org/api/v2/doc/doc",
            {"query": query, "mode": "ArtList", "maxrecords": str(rows),
             "format": "json", "sort": "DateDesc"}, {}, "GET", None)


def extract(data):
    hits = []
    for a in ((data or {}).get("articles") or []):
        hits.append({
            "title": a.get("title") or "(无题)",
            "url": a.get("url") or "",
            "meta": [m for m in [a.get("seendate") or "",
                                 a.get("domain") or "",
                                 a.get("language") or ""] if m],
            "excerpt": (a.get("snippet")
                        or a.get("title") or "")[:1500],
        })
    return hits


if __name__ == "__main__":
    raise SystemExit(core.run(SPEC))

