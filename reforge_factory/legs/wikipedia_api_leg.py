from __future__ import annotations

import re
import sys
from pathlib import Path
from urllib.parse import quote

sys.path.insert(0, str(Path(__file__).resolve().parent))
import http_api_leg_core as core

SPEC = {"engine": "wikipedia_api", "source": "Wikipedia API (list=search)",
        "note": "A级·标准定额·免登录API; batch1025实装: GET JSON list=search/srlimit"}


def endpoint(query, rows):
    return ("https://zh.wikipedia.org/w/api.php",
            {"action": "query", "list": "search", "srsearch": query,
             "srlimit": str(rows), "format": "json"}, {}, "GET", None)


def extract(data):
    res = (((data or {}).get("query") or {}).get("search")) or []
    hits = []
    for s in res:
        title = s.get("title") or "(无题)"
        hits.append({
            "title": title,
            "url": "https://zh.wikipedia.org/wiki/"
                   + quote(title, safe=""),
            "meta": [m for m in ["%s词" % s.get("wordcount"),
                                 str(s.get("timestamp") or "")[:10]] if m],
            "excerpt": re.sub(r"<[^>]+>", "", s.get("snippet") or ""),
        })
    return hits


if __name__ == "__main__":
    raise SystemExit(core.run(SPEC))

