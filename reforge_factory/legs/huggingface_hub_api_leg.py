SPEC = {"engine": "huggingface_hub_api", "source": "HuggingFace Hub API (models search)",
        "note": "A级·数据集·免登录API(限速); batch1025实装: GET JSON search/limit (模型面)"}


def endpoint(query, rows):
    return ("https://huggingface.co/api/models",
            {"search": query, "limit": str(rows)}, {}, "GET", None)


def extract(data):
    hits = []
    if isinstance(data, list):
        for mm in data:
            ident = mm.get("id") or "(无题)"
            hits.append({
                "title": ident,
                "url": "https://huggingface.co/" + ident,
                "meta": [m for m in [mm.get("pipeline_tag") or "",
                                     "%s下载" % mm.get("downloads"),
                                     "%s赞" % mm.get("likes")] if m],
                "excerpt": "HF Hub 模型面: %s (downloads=%s, likes=%s)"
                           % (ident, mm.get("downloads"),
                              mm.get("likes")),
            })
    return hits


if __name__ == "__main__":
    raise SystemExit(core.run(SPEC))

