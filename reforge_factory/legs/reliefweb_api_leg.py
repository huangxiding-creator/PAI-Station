from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import http_api_leg_core as core

SPEC = {"engine": "reliefweb_api", "source": "ReliefWeb API v1 (reports)",
        "note": "A级·新闻舆情/项目数据·免登录API; batch1025实装: GET JSON appname/query[value]/fields[]"}


def endpoint(query, rows):
    return ("https://api.reliefweb.int/v1/reports",
            {"appname": "ai-station-research-leg",
             "query[value]": query, "limit": str(rows),
             "sort[]": "date:desc",
             "fields[include][]": ["title", "url", "source.shortname",
                                   "date.created"]},
            {}, "GET", None)


def extract(data):
    hits = []
    for d in ((data or {}).get("data") or []):
        f = d.get("fields") or {}
        src = f.get("source") or []
        if not isinstance(src, list):
            src = [src]
        srcname = ", ".join(s.get("shortname") or s.get("name") or ""
                            for s in src if isinstance(s, dict))
        title = f.get("title") or "(无题)"
        hits.append({
            "title": title,
            "url": f.get("url") or "",
            "meta": [m for m in [srcname,
                                 str((f.get("date") or {})
                                     .get("created") or "")[:10]] if m],
            "excerpt": "ReliefWeb 人道报告: %s (来源: %s)"
                       % (title, srcname or "-"),
        })
    return hits


if __name__ == "__main__":
    raise SystemExit(core.run(SPEC))

