def endpoint(query, rows):
    return ("https://www.baidu.com/s",
            {"wd": query, "rn": str(rows)}, {}, "GET", None)


def extract(data):
    if not isinstance(data, str):
        return []
    hits, seen = [], set()
    for m in re.finditer(
            r'<h3[^>]*>\s*<a[^>]+href="(http[^"]+)"[^>]*>(.*?)</a>',
            data, re.S):
        url = m.group(1)
        if url in seen:
            continue
        seen.add(url)
        title = re.sub(r"<[^>]+>", "", m.group(2)).strip()
        if not title:
            continue
        hits.append({
            "title": title,
            "url": url,
            "meta": ["百度SERP(跳转链)"],
            "excerpt": "百度结果: %s (百度跳转链, 实链resolve待接; "
                       "风控面(需cookie/验证码)则如实失败)" % title,
        })
    return hits


