def test_golden_corpus_shape():
    assert len(CORPUS) == 20
    assert len(QUESTIONS) == 100
    # 作者纪律自检：每问要么自带锚词，要么是正文原句（检索词即落点）
    bodies = {name: body for name, body, _qas in CORPUS}
    for query, name, anchor in QUESTIONS:
        assert anchor in query or query in bodies[name], (query, anchor)


def test_full_chain_extraction_report(universe):
    r = universe["report"]
