def test_like_fallback_for_two_char_term(universe):
    """2 字词跳过 FTS 走 LIKE 兜底，且只命中台账文档。"""
    hits = universe["chunks"].search("台账", k=3)
    assert hits and all(h.source == "like" for h in hits)
    assert all("安全生产费用管理" in h.path for h in hits)


def test_secret_file_never_surfaces(universe):
    """红线：secret 蜜罐内容检索零命中、路径检索默认缺席。"""
    for probe in ("银行账号", "密码清单", "token"):
        for h in universe["chunks"].search(probe, k=8):
            assert SECRET_NAME not in h.path
    assert universe["chunks"].search("银行账号", k=8) == []
    assert universe["inv"].search_paths("密码本") == []
    rows = universe["inv"].search_paths("密码本", include_secret=True)
    assert len(rows) == 1 and SECRET_NAME in rows[0]["path"]
